std::map<std::string, PreferenceValue> 
EnvironmentPreferenceResolver::resolve_from_environment() {
    std::map<std::string, PreferenceValue> prefs;
    
    // Check for REBUNTU_PREFERENCE_* environment variables
    for (char** env = environ; *env != nullptr; ++env) {
        std::string entry(*env);
        
        // Look for REBUNTU_PREFERENCE_<ID>=VALUE format
        size_t pos = entry.find("REBUNTU_PREFERENCE_");
        if (pos == 0) {
            size_t eq_pos = entry.find('=');
            if (eq_pos != std::string::npos) {
                std::string id = entry.substr(19, eq_pos - 19);  // 19 = len("REBUNTU_PREFERENCE_")
                std::string value = entry.substr(eq_pos + 1);
                
                PreferenceValue pv;
                pv.id = id;
                pv.selected_value = value;
                pv.scope = PreferenceScope::kSession;  // Environment vars are session-scoped
                pv.source = PreferenceValue::Source::kEnvironment;
                
                prefs[id] = std::move(pv);
            }
        }
    }
    
    return prefs;
}

std::optional<PreferenceValue> 
EnvironmentPreferenceResolver::get_env_preference(std::string_view pref_id) {
    std::string var_name = "REBUNTU_PREFERENCE_" + std::string{pref_id};
    const char* value = std::getenv(var_name.c_str());
    
    if (value == nullptr) return std::nullopt;
    
    PreferenceValue pv;
    pv.id = std::string{pref_id};
    pv.selected_value = value;
    pv.scope = PreferenceScope::kSession;
    pv.source = PreferenceValue::Source::kEnvironment;
    
    return pv;
}

// ============================================================================
// SessionPreferences Implementation
// ============================================================================

std::map<std::string, PreferenceValue> 
SessionPreferences::load() const {
    // For now, session preferences are just the in-memory values
    return session_values_;
}

void SessionPreferences::set(std::string id, std::string value) {
    session_values_[id].id = std::move(id);
    session_values_[id].selected_value = std::move(value);
    session_values_[id].scope = PreferenceScope::kSession;
    session_values_[id].source = PreferenceValue::Source::kInvocation;  // Session override
}

void SessionPreferences::clear() {
    session_values_.clear();
}

std::map<std::string, PreferenceValue> 
SessionPreferences::get_all() const {
    return session_values_;
}

